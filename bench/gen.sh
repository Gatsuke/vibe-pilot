#!/usr/bin/env bash
# vibe-pilot benchmark fixture generator.
# Builds a deterministic, realistically-messy TypeScript app in /tmp so
# anyone can reproduce the README numbers:  make bench
set -euo pipefail

ROOT="${VP_BENCH_DIR:-/tmp/vp-bench-app}"
rm -rf "$ROOT"
mkdir -p "$ROOT"/{src/{api,auth,components,hooks,lib,store,generated},tests,docs,node_modules/express,public}

# ---- manifests ----
cat > "$ROOT/package.json" <<'EOF'
{
  "name": "legacy-shop",
  "version": "3.7.2",
  "private": true,
  "main": "src/index.ts",
  "scripts": { "dev": "vite", "test": "vitest", "build": "vite build" }
}
EOF

# ---- lockfile: ~14k lines of honest pain ----
{
  echo '{'
  echo '  "name": "legacy-shop",'
  echo '  "lockfileVersion": 3,'
  echo '  "packages": {'
  for i in $(seq 1 1400); do
    echo "    \"node_modules/dep-$i\": {"
    echo "      \"version\": \"1.$i.0\","
    echo "      \"resolved\": \"https://registry.npmjs.org/dep-$i/-/dep-$i-1.$i.0.tgz\","
    echo "      \"integrity\": \"sha512-$(printf '%064d' $i)\","
    echo "      \"requires\": { \"dep-$((i % 50 + 1))\": \"^1.0.0\" }"
    echo '    },'
  done
  echo '    "": { "name": "legacy-shop", "dependencies": { "react": "^19.0.0" } }'
  echo '  }'
  echo '}'
} > "$ROOT/package-lock.json"

# ---- 180 source files with comments + blank-line padding ----
gen_source () {
  local file="$1" idx="$2" mod="$3"
  cat > "$file" <<EOF
// legacy-shop module $idx
// (c) 2021-2026 Legacy Corp — all rights reserved
// Module: $mod — auto-managed by the platform team

import { api } from "../api/client";
import { config } from "../lib/config";
import type { Session } from "../auth/session";

//
// $mod implementation
//

export interface ${mod}Props {

  id: string;
  label: string;
  values: Record<string, unknown>;

}

export function use$mod(session: Session) {

  const state = api.fetch("$mod/" + session.id);
  const merged = { ...state, config };

  return {

    ...merged,
    reload: () => api.fetch("$mod/reload"),
    serialize: () => JSON.stringify(merged.values),

  };

}

export default use$mod;
EOF
}

for i in $(seq 1 180); do
  case $((i % 4)) in
    0) mod="Product" ;;
    1) mod="Cart" ;;
    2) mod="Order" ;;
    *) mod="Invoice" ;;
  esac
  dir="src/lib"; [ $((i % 3)) -eq 0 ] && dir="src/components"; [ $((i % 5)) -eq 0 ] && dir="src/hooks"
  gen_source "$ROOT/$dir/${mod,,}$i.ts" "$i" "$mod"
done

# ---- entry + auth (the "actively developed" files) ----
cat > "$ROOT/src/index.ts" <<'EOF'
// legacy-shop entrypoint
import { useCart } from "./lib/cart1";
import { useInvoice } from "./lib/invoice2";

const app = { cart: useCart, invoice: useInvoice };
export default app;
EOF

cat > "$ROOT/src/auth/session.ts" <<'EOF'
// session handling — we are fixing the refresh bug here
export type Session = { id: string; token: string; exp: number };

export function refresh(s: Session): Session {
  if (s.exp < Date.now() / 1000) {
    return { ...s, token: s.token + "-r", exp: Date.now() / 1000 + 3600 };
  }
  return s;
}
EOF

# ---- generated API client: 3,200 lines ----
{
  echo "// @generated by openapi-ts — DO NOT EDIT"
  echo "/* eslint-disable */"
  for i in $(seq 1 1050); do
    echo "export const endpoint$i = (params$i: Params$i) => fetch('/api/v1/ep$i', params$i);"
    echo "type Params$i = { id$i: number; q$i: string };"
  done
} > "$ROOT/src/generated/api.ts"

# ---- tests ----
for i in $(seq 1 30); do
  cat > "$ROOT/tests/cart${i}.test.ts" <<EOF
import { describe, it, expect } from "vitest";
import { useCart } from "../src/lib/cart$i";

describe("cart $i", () => {
  it("loads", () => expect(useCart).toBeDefined());
  it("serializes", () => expect(typeof useCart).toBe("function"));
  it("reloads", () => expect(true).toBe(true));
});
EOF
done

# ---- docs ----
for i in $(seq 1 8); do
  printf '# Legacy Shop Doc %s\n\nChapter %s of the internal documentation.\n lorem ipsum dolor sit amet %s\n\n- bullet one\n- bullet two\n\nMore prose to pad the token count for realistic measurements.\n' "$i" "$i" "$i" > "$ROOT/docs/doc$i.md"
done
printf '# legacy-shop\n\nInternal storefront. See docs/ for architecture.\n' > "$ROOT/README.md"
printf '# rules\n\nTypeScript strict. No any. Tests colocated in tests/.\n' > "$ROOT/CLAUDE.md"

# ---- config noise ----
cat > "$ROOT/.env" <<'EOF'
STRIPE_SECRET=sk_live_51FakeFakeFake
JWT_SECRET=super-secret-do-not-commit
EOF
printf 'STRIPE_SECRET=changeme\n' > "$ROOT/.env.example"
printf 'node_modules/\ndist/\n' > "$ROOT/.gitignore"
printf 'FROM node:24\nWORKDIR /app\nCOPY . .\nRUN npm ci\nCMD ["npm","start"]\n' > "$ROOT/Dockerfile"
printf 'services:\n  web:\n    build: .\n    ports: ["3000:3000"]\n' > "$ROOT/docker-compose.yml"

# ---- vendor junk (should never be scanned) ----
for i in $(seq 1 60); do
  printf 'module.exports = function dep%d() { return %d; };\n' "$i" "$i" > "$ROOT/node_modules/express/dep$i.js"
done
printf '\x89PNG\r\n\x1a\nfakepngdata' > "$ROOT/public/logo.png"

echo "fixture ready: $ROOT"
echo "  files: $(find "$ROOT" -type f | wc -l) (incl. node_modules junk)"

//! The `.context` format: a self-describing markdown file your AI assistant
//! can actually reason about. Open spec — see docs/CONTEXT-SPEC.md.

use crate::pipeline::{Options, Scan, Stats};
use crate::profiler::fence_of;
use crate::tokens;
use crate::util::{iso8601, now_secs, pct, thousands};

/// Maximum lines in the map section (monorepo safety).
const MAP_LIMIT: usize = 1_500;

pub fn render(scan: &mut Scan, opts: &Options, stats: &Stats) -> String {
    let strip = opts.strip();
    let mut out = String::with_capacity(64 * 1024);

    let branch = scan
        .git
        .as_ref()
        .map(|g| g.branch.as_str())
        .unwrap_or("no-git");

    // ---- header ----
    out.push_str(&format!("# context · {} · {}\n\n", scan.name, branch));
    out.push_str(&format!(
        "> generated by vibe-pilot v{} · profile: {}",
        crate::VERSION,
        opts.profile.name
    ));
    if let Some(t) = &opts.task {
        out.push_str(&format!(" · task: \"{}\"", t));
    }
    if opts.diff_only {
        out.push_str(" · scope: changed files only");
    }
    out.push('\n');
    out.push_str(&format!("> {} UTC\n", iso8601(now_secs())));
    out.push_str("> this file is your project context. files not included are listed in the map below with scores - ask for any of them by path.\n\n");

    // ---- stats ----
    let files_pct = if stats.files_total > 0 {
        stats.files_selected as f64 * 100.0 / stats.files_total as f64
    } else {
        0.0
    };
    out.push_str("## stats\n\n");
    out.push_str("| metric | value |\n| --- | --- |\n");
    out.push_str(&format!(
        "| files | {} of {} ({:.1}%) |\n",
        stats.files_selected, stats.files_total, files_pct
    ));
    out.push_str(&format!(
        "| tokens (est) | {} — raw {} ({}) |\n",
        thousands(stats.out_tokens),
        thousands(stats.raw_tokens),
        pct(stats.reduction())
    ));
    out.push_str(&format!(
        "| cost / prompt | {} — was {} · {} @ ${}/MTok |\n",
        tokens::fmt_cost(stats.cost_out),
        tokens::fmt_cost(stats.cost_raw),
        stats.model,
        stats.price_in
    ));
    out.push_str(&format!(
        "| repo | {} · {} · {} |\n\n",
        scan.name,
        if scan.project.primary.is_empty() {
            "unknown-lang"
        } else {
            &scan.project.primary
        },
        branch
    ));

    // ---- task focus ----
    if let Some(task) = &opts.task {
        let terms = crate::ranker::task_terms(task);
        if !terms.is_empty() {
            let mut hits: Vec<&crate::pipeline::FileAnalysis> = scan
                .files
                .iter()
                .filter(|f| f.task_hits > 0.0 && f.selected)
                .collect();
            hits.sort_by(|a, b| {
                b.task_hits
                    .partial_cmp(&a.task_hits)
                    .unwrap_or(std::cmp::Ordering::Equal)
            });
            if !hits.is_empty() {
                out.push_str("## task focus\n\n");
                out.push_str(&format!(
                    "terms: {}. best-matching included files:\n\n",
                    terms.join(", ")
                ));
                for f in hits.iter().take(5) {
                    out.push_str(&format!(
                        "- `{}` · {}/{} terms\n",
                        f.rel,
                        (f.task_hits * terms.len() as f64).round() as usize,
                        terms.len()
                    ));
                }
                out.push('\n');
            }
        }
    }

    // ---- changed ----
    if opts.diff_only {
        if let Some(g) = &scan.git {
            out.push_str("## changed\n\n");
            if g.changed.is_empty() {
                out.push_str("_no uncommitted changes vs HEAD_\n\n");
            } else {
                for c in &g.changed {
                    out.push_str(&format!("- {} `{}`\n", c.status, c.rel));
                }
                out.push('\n');
            }
        }
    }

    // ---- map ----
    out.push_str("## map\n\n");
    let mut sorted: Vec<&crate::pipeline::FileAnalysis> = scan.files.iter().collect();
    sorted.sort_by(|a, b| {
        b.score
            .partial_cmp(&a.score)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then(a.rel.cmp(&b.rel))
    });
    let mut lines = 0;
    let mut skipped_maps = 0usize;
    for f in &sorted {
        if lines >= MAP_LIMIT {
            skipped_maps += 1;
            continue;
        }
        lines += 1;
        let mut line = format!(
            "- `{}` · {} · {} tok",
            f.rel,
            f.kind.label(),
            crate::util::human_count(f.tokens_raw)
        );
        if f.score > 0.0 {
            line.push_str(&format!(" · score {:.1}", f.score));
        }
        if !f.selected {
            line.push_str(&format!(" · NOT included ({})", f.reason));
        }
        out.push_str(&line);
        out.push('\n');
    }
    if skipped_maps > 0 {
        out.push_str(&format!(
            "- ... {} more files (raise the budget or check .gitignore)\n",
            skipped_maps
        ));
    }
    out.push('\n');

    // ---- files ----
    out.push_str("## files\n\n");
    let mut selected: Vec<usize> = (0..scan.files.len())
        .filter(|&i| scan.files[i].selected)
        .collect();
    selected.sort_by(|&a, &b| {
        scan.files[b]
            .score
            .partial_cmp(&scan.files[a].score)
            .unwrap_or(std::cmp::Ordering::Equal)
            .then(scan.files[a].rel.cmp(&scan.files[b].rel))
    });
    for i in selected {
        let (rel, ext, score) = {
            let f = &scan.files[i];
            (f.rel.clone(), f.ext.clone(), f.score)
        };
        let content = scan.files[i].pruned_content(strip);
        out.push_str(&format!(
            "### `{}` — {} tok · score {:.1}\n\n",
            rel,
            crate::util::human_count(tokens::estimate(&content)),
            score
        ));
        let fence = fence_for(&content, &ext);
        out.push_str(&format!("```{}\n", fence));
        if content.is_empty() {
            out.push_str("(empty after pruning)\n");
        } else {
            out.push_str(&content);
            if !content.ends_with('\n') {
                out.push('\n');
            }
        }
        out.push_str("```\n\n");
    }

    out
}

/// Pick a fence longer than any backtick run inside the content.
fn fence_for(content: &str, ext: &str) -> String {
    let mut max_run = 0;
    let mut cur = 0;
    for c in content.chars() {
        if c == '`' {
            cur += 1;
            max_run = max_run.max(cur);
        } else {
            cur = 0;
        }
    }
    let n = 3.max(max_run + 1);
    let fence_lang = fence_of(ext);
    format!(
        "{}{}",
        "`".repeat(n),
        if fence_lang.is_empty() {
            String::new()
        } else {
            fence_lang.to_string()
        }
    )
}

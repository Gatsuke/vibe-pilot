//! End-to-end tests on a synthetic repo fixture.

use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU32, Ordering};

use vibe_pilot::config;
use vibe_pilot::pipeline::{self, Options};
use vibe_pilot::profiler::{self, Kind};

static COUNTER: AtomicU32 = AtomicU32::new(0);

fn fixture(name: &str) -> PathBuf {
    let n = COUNTER.fetch_add(1, Ordering::SeqCst);
    let dir = std::env::temp_dir().join(format!("vp-test-{}-{}", name, n));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(dir.join("src/auth")).unwrap();
    fs::create_dir_all(dir.join("src/generated")).unwrap();
    fs::create_dir_all(dir.join("src/util")).unwrap();
    fs::create_dir_all(dir.join("tests")).unwrap();
    fs::create_dir_all(dir.join("node_modules/express")).unwrap();
    fs::create_dir_all(dir.join("docs")).unwrap();
    dir
}

fn write(root: &Path, rel: &str, content: &str) {
    let p = root.join(rel);
    fs::create_dir_all(p.parent().unwrap()).unwrap();
    fs::write(p, content).unwrap();
}

fn opts(profile: &str, task: Option<&str>) -> Options {
    Options {
        profile: config::builtin(profile).unwrap(),
        task: task.map(|s| s.to_string()),
        diff_only: false,
        max_tokens: None,
        strip_comments: None,
        ignore: vec![],
        model: "claude-sonnet-5.5".into(),
        price_override: None,
    }
}

fn build_typical_app(root: &Path) {
    write(
        root,
        "package.json",
        r#"{ "name": "app", "main": "src/index.ts" }"#,
    );
    write(
        root,
        "src/index.ts",
        "// entry\nimport { login } from \"./auth/login\";\n\n\n\nconsole.log(login);\n",
    );
    write(
        root,
        "src/auth/login.ts",
        "// login flow\nexport function login(user: string, pass: string) {\n  const token = signIn(user, pass);\n  return token;\n}\n",
    );
    write(
        root,
        "src/auth/session.ts",
        "export function session(token: string) {\n  return token.length > 0;\n}\n",
    );
    write(
        root,
        "src/util/format.ts",
        "export const fmt = (s: string) => s.trim();\n",
    );
    write(
        root,
        "src/generated/api.ts",
        "// @generated by openapi-codegen — do not edit\nexport const endpoints = [1,2,3];\n",
    );
    write(
        root,
        "package-lock.json",
        &"{\"lockfileVersion\": 3}".repeat(2000),
    );
    write(
        root,
        "tests/login.test.ts",
        "import { login } from \"../src/auth/login\";\ntest(\"login\", () => login(\"a\", \"b\"));\n",
    );
    write(root, "README.md", "# app\nA test app.\n");
    write(root, "CLAUDE.md", "# rules\nAlways use TypeScript.\n");
    write(root, "docs/architecture.md", "# architecture\nWords.\n");
    write(root, ".env", "AWS_SECRET=supersecret\n");
    write(root, ".env.example", "AWS_SECRET=changeme\n");
    write(
        root,
        "node_modules/express/index.js",
        "module.exports = {};\n",
    );
    write(root, ".gitignore", "node_modules/\n");
    write(root, "logo.png", "\u{0}\u{1}fakepng");
}

#[test]
fn walker_respects_gitignore_and_builtins() {
    let root = fixture("walk");
    build_typical_app(&root);
    let w = vibe_pilot::walker::walk(&root, &[]);
    let rels: Vec<&str> = w.files.iter().map(|f| f.rel.as_str()).collect();
    assert!(rels.contains(&"src/auth/login.ts"));
    assert!(rels.contains(&"package-lock.json")); // walked, classified later
    assert!(!rels.iter().any(|r| r.starts_with("node_modules/")));
}

#[test]
fn classification_and_secrets() {
    let root = fixture("classify");
    build_typical_app(&root);
    let o = opts("claude", None);
    let scan = pipeline::scan(&root, &o);
    let find = |rel: &str| scan.files.iter().find(|f| f.rel == rel).unwrap();
    assert_eq!(find("package-lock.json").kind, Kind::Lockfile);
    assert_eq!(find("src/generated/api.ts").kind, Kind::Generated);
    assert_eq!(find("tests/login.test.ts").kind, Kind::Test);
    assert_eq!(find("CLAUDE.md").kind, Kind::Rules);
    assert_eq!(find(".env").kind, Kind::Secret);
    // secrets are never read
    assert!(find(".env").raw.is_empty());
    assert_eq!(find("src/auth/login.ts").kind, Kind::Source);
}

#[test]
fn raw_tokens_count_everything_text() {
    let root = fixture("rawcount");
    build_typical_app(&root);
    let o = opts("claude", None);
    let scan = pipeline::scan(&root, &o);
    // lockfile contributes the bulk of the raw bill
    let lock = scan
        .files
        .iter()
        .find(|f| f.rel == "package-lock.json")
        .unwrap();
    assert!(
        lock.tokens_raw > 10_000,
        "lockfile tokens: {}",
        lock.tokens_raw
    );
    assert!(scan.raw_tokens > lock.tokens_raw);
}

#[test]
fn task_context_ranks_and_emits() {
    let root = fixture("taskctx");
    build_typical_app(&root);
    let o = opts("claude", Some("fix the login token bug"));
    let mut scan = pipeline::scan(&root, &o);
    let emitted = pipeline::emit(&mut scan, &o);

    // login.ts should outrank unrelated util
    let login = scan
        .files
        .iter()
        .find(|f| f.rel == "src/auth/login.ts")
        .unwrap();
    let util = scan
        .files
        .iter()
        .find(|f| f.rel == "src/util/format.ts")
        .unwrap();
    assert!(
        login.score > util.score,
        "login {:.2} vs util {:.2}",
        login.score,
        util.score
    );
    assert!(login.task_hits > 0.0);

    // .context structure
    assert!(emitted.content.contains("# context · vp-test-taskctx"));
    assert!(emitted.content.contains("## stats"));
    assert!(emitted.content.contains("## map"));
    assert!(emitted.content.contains("## files"));
    assert!(emitted.content.contains("### `src/auth/login.ts`"));
    assert!(emitted.content.contains("task focus"));

    // lockfile + secrets never leak into the body
    assert!(!emitted.content.contains("lockfileVersion"));
    assert!(!emitted.content.contains("supersecret"));

    // budget respected (claude = 60k)
    assert!(emitted.stats.out_tokens <= 60_000);
    // and massively smaller than raw
    assert!(
        emitted.stats.reduction() > 0.9,
        "reduction {}",
        emitted.stats.reduction()
    );
}


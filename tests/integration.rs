#[test]
fn budget_hard_cap() {
    let root = fixture("cap");
    build_typical_app(&root);
    let mut o = opts("claude", None);
    o.max_tokens = Some(1_200);
    let mut scan = pipeline::scan(&root, &o);
    let emitted = pipeline::emit(&mut scan, &o);
    assert!(
        emitted.stats.out_tokens <= 1_200,
        "got {}",
        emitted.stats.out_tokens
    );
    // map section still present even under a brutal budget
    assert!(emitted.content.contains("## map"));
}

#[test]
fn generated_and_lockfile_never_included() {
    let root = fixture("never");
    build_typical_app(&root);
    for prof in ["lean", "cursor", "windsurf", "aider", "claude", "full"] {
        let o = opts(prof, None);
        let mut scan = pipeline::scan(&root, &o);
        let emitted = pipeline::emit(&mut scan, &o);
        assert!(
            !emitted.content.contains("### `package-lock.json`"),
            "{} included lockfile",
            prof
        );
        assert!(
            !emitted.content.contains("### `src/generated/api.ts`"),
            "{} included generated",
            prof
        );
        assert!(
            !emitted.content.contains("### `.env`"),
            "{} included secret",
            prof
        );
    }
}

#[test]
fn projections_cover_all_profiles() {
    let root = fixture("proj");
    build_typical_app(&root);
    let o = opts("claude", None);
    let mut scan = pipeline::scan(&root, &o);
    let p = pipeline::project_stats(&mut scan, &o);
    assert_eq!(p.len(), 6);
    for proj in &p {
        assert!(proj.tokens > 0, "{} empty", proj.profile);
        assert!(
            proj.reduction > 0.5,
            "{} reduction {}",
            proj.profile,
            proj.reduction
        );
    }
    // lean should be smaller than full
    let lean = p.iter().find(|x| x.profile == "lean").unwrap();
    let full = p.iter().find(|x| x.profile == "full").unwrap();
    assert!(lean.tokens < full.tokens);
}

